"""Сборка system prompt из фиксированного набора файлов."""
from __future__ import annotations

from .config import PROMPTS_DIR
from .library_api import read_text


PROMPT_ORDER = [
    "system_base.txt",
    "addon_mapping.txt",
    "addon_checklist.txt",
    "addon_anti_examples.txt",
    "addon_hard_rules.txt",
    "addon_environment_api.txt",
    "addon_examples.txt",
]

# Сколько последних успешных турнов диалога подмешивать в промпт при
# включённом "Отправить в тот же чат" (см. toggle0 в new_ui.py).
# Единственное место, где это число определено — run.py импортирует
# его отсюда, чтобы не было двух разных источников правды.
MAX_HISTORY_TURNS = 3


def _load_library_rules() -> str:
    parts = []
    for name in PROMPT_ORDER:
        path = PROMPTS_DIR / name
        if path.is_file():
            text = read_text(path).strip()
            if text:
                parts.append(text)

    if not parts:
        legacy = PROMPTS_DIR / "system_prompt.txt"
        if legacy.is_file():
            parts.append(read_text(legacy).strip())

    return "\n\n".join(parts)


def _history_block(history: list[dict]) -> str:
    """
    Блок с предыдущими успешными турнами этой же "сессии" (см. toggle
    "Отправить в тот же чат" в new_ui.py). Вставляется ДО USER REQUEST,
    чтобы модель сначала увидела, что уже построено, а потом — сам
    новый запрос и инструкцию по формату ответа.
    """
    turns = history[-MAX_HISTORY_TURNS:]
    blocks = []
    for i, turn in enumerate(turns, 1):
        req = turn.get("request", "")
        code = turn.get("code", "")
        blocks.append(
            f"--- Предыдущий запрос {i} из {len(turns)} (этой же сессии) ---\n"
            f"Запрос пользователя: {req}\n"
            "Сгенерированный и успешно выполненный в NX код:\n"
            "--------------------------------------------------------------------------------\n"
            f"{code}\n"
            "--------------------------------------------------------------------------------\n"
        )
    return (
    "================================================================================\n"
    "КОНТЕКСТ ПРЕДЫДУЩИХ ЗАПРОСОВ ЭТОЙ ЖЕ СЕССИИ\n"
    "================================================================================\n\n"
    + "\n".join(blocks) +
    "\nНовый USER REQUEST ниже нужно рассматривать как ПРОДОЛЖЕНИЕ/ИЗМЕНЕНИЕ уже "
    "построенной модели с точки зрения ЗАМЫСЛА и стиля — используй тот же подход "
    "к геометрии, что и в предыдущем коде, где это уместно. "
    "ВАЖНО: 3D-холст сейчас может быть пуст (например, после очистки), поэтому "
    "КАЖДЫЙ раз генерируй ПОЛНЫЙ самостоятельный код, который заново строит ВСЮ "
    "геометрию с нуля (включая то, что было в предыдущем коде), а не только новую "
    "часть — предыдущий код показан только как СПРАВКА о том, что уже было "
    "сделано, а не как код, который уже выполнен в текущей сессии.\n\n"
    "ОСОБО ВАЖНО про Union/Subtract/Intersect и правило МИНИМАЛЬНОСТИ: правило "
    "«нет слова объединить → нет Union» применяется к СМЫСЛУ ВСЕЙ модели, а не "
    "только к тексту последнего сообщения. Если в ПРЕДЫДУЩЕМ коде этой сессии "
    "уже было Union (тела уже объединены по замыслу пользователя), а новый "
    "запрос лишь просит что-то ДОБАВИТЬ или ИЗМЕНИТЬ на этой же объединённой "
    "модели (например, скруглить шов, добавить ещё одну деталь и т.п.) — "
    "Union НУЖНО сохранить в новом коде, даже если слово «объединить» не "
    "повторено в новом запросе. Особый случай: если новый запрос просит "
    "скруглить/сделать фаску именно ШВА/ПЕРЕХОДА/СТЫКА между телами — Fillet "
    "шва физически невозможен без Union (шва как геометрии не существует у "
    "раздельных Extrude), поэтому Union обязателен, и seam-функция "
    "(attach_plate_seam/attachment_seam) должна получать merged.body, а НЕ "
    "body отдельного Extrude."
    )


def build_prompt(user_request: str, history: list[dict] | None = None) -> str:
    """
    Собирает финальный промпт:
      1) все куски промпта по PROMPT_ORDER (всегда целиком)
      2) (опционально) контекст предыдущих запросов той же сессии — ДО USER REQUEST
      3) USER REQUEST
      4) IMPORTANT (жёсткое требование к формату ответа) — последним, ближе к концу
    """
    parts = [_load_library_rules()]

    if history:
        parts.append(_history_block(history))

    parts.append(
        "================================================================================\n"
        "USER REQUEST\n"
        "================================================================================\n\n"
        f"{user_request}\n\n"
        "================================================================================\n"
        "IMPORTANT\n\n"
        "Return ONLY executable Python code.\n"
        "Do NOT explain anything.\n"
        "Do NOT use Markdown.\n"
        "Do NOT wrap the code with ```.\n"
        "The answer must consist ONLY of Python code.\n"
        "================================================================================"
    )
    return "\n\n".join(parts)